# glyph lookup: char -> 7 rows of 5 bits each
glyph_rows = {}
for ch, rows in _GLYPHS.items():
    glyph_rows[ord(ch)] = [int(r, 2) for r in rows]

# fallback block for any character not defined
_BLOCK = [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F]


def glyph(ch):
    return glyph_rows.get(ord(ch), _BLOCK)


def text_width(text, scale=1):
    return len(text) * 6 * scale - scale


def draw_text(buf, w, h, x, y, text, color, scale=2, bg=None):
    """Draw text upper-cased (5x7 font) into RGB565 big-endian buf.

    buf: bytearray of w*h*2.
    Returns the bounding width drawn.
    """
    hi, lo = color          # (high, low) RGB565 big-endian bytes as returned by rgb255
    bgh = bgl = None
    if bg is not None:
        bgh, bgl = bg
    g = 6 * scale
    for ch in text.upper():
        rows = glyph(ch)
        for r in range(7):
            bits = rows[r]
            for c in range(5):
                on = (bits >> (4 - c)) & 1
                for sy in range(scale):
                    for sx in range(scale):
                        px = x + c * scale + sx
                        py = y + r * scale + sy
                        if 0 <= px < w and 0 <= py < h:
                            off = (py * w + px) * 2
                            if on:
                                buf[off] = hi
                                buf[off + 1] = lo
                            elif bg is not None:
                                buf[off] = bgh
                                buf[off + 1] = bgl
        x += g
    return x